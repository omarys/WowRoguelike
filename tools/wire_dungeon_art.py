def as_tile(im: Image.Image) -> Image.Image:
    return im.resize((40, 40), Image.LANCZOS)


def as_tile_center(im: Image.Image) -> Image.Image:
    # Crop the clean central flagstones (trimming corner cobwebs) so repeated
    # monastery floor tiles read as crisp, even stone masonry.
    w, h = im.size
    mx, my = round(w * 0.17), round(h * 0.17)
    return im.crop((mx, my, w - mx, h - my)).resize((40, 40), Image.LANCZOS)


def as_decor(im: Image.Image) -> Image.Image:
    scale = 36 / max(im.size)
    return im.resize((max(1, round(im.width * scale)), max(1, round(im.height * scale))), Image.LANCZOS)


def as_sprite(im: Image.Image) -> Image.Image:
    # Fit into 48x48 keeping aspect; bottom-align so the feet stand on the tile.
    scale = 48 / max(im.size)
    w, h = max(1, round(im.width * scale)), max(1, round(im.height * scale))
    art = im.resize((w, h), Image.LANCZOS)
    canvas = Image.new("RGBA", (48, 48), (0, 0, 0, 0))
    canvas.paste(art, ((48 - w) // 2, 48 - h), art)
    return canvas


MAKERS = {"tile": as_tile, "tile_center": as_tile_center, "decor": as_decor, "sprite": as_sprite}


def main() -> None:
    for folder, src, key, kind in MANIFEST:
        im = Image.open(SRC / folder / src).convert("RGBA")
        out = DST / (key + ".png")
        out.parent.mkdir(parents=True, exist_ok=True)
        MAKERS[kind](im).save(out)
        print(f"{folder}/{src} -> {out.relative_to(REPO)} ({kind})")


if __name__ == "__main__":
    main()
